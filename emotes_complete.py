def find_emote_complete(query: str) -> str:
    """Trouve un emote par nom (supporte espaces et variations)"""
    query = query.lower().strip()
    
    # Recherche exacte dans les alias
    if query in EMOTE_ALIASES:
        return EMOTE_ALIASES[query]
    
    # Recherche exacte dans les emotes
    if query in EMOTES_COMPLETE:
        return EMOTES_COMPLETE[query]
    
    # Recherche partielle dans les alias
    for name, emote_id in EMOTE_ALIASES.items():
        if query in name or name in query:
            return emote_id
    
    # Recherche partielle dans les emotes
    for name, emote_id in EMOTES_COMPLETE.items():
        if query in name or name in query:
            return emote_id
    
    return None

def get_emote_count_complete() -> int:
    """Retourne le nombre total d'emotes"""
    return len(set(EMOTES_COMPLETE.values()))

def get_random_emote_complete() -> str:
    """Retourne un emote aléatoire"""
    import random
    return random.choice(list(EMOTES_COMPLETE.values()))
